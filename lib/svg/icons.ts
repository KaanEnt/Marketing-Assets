export const ICON_NAMES = Object.keys(ICONS);

export function isIconName(name: string): boolean {
  return Object.hasOwn(ICONS, name);
}

/**
 * Replace every <g data-icon="..."> placeholder with real glyph geometry.
 *
 * Idempotent: a group that already has children is left alone, so re-running
 * after a re-render does not stack duplicate paths.
 */
export function resolveIcons(root: SVGSVGElement | Element): number {
  let resolved = 0;

  for (const group of Array.from(root.querySelectorAll("[data-icon]"))) {
    const name = group.getAttribute("data-icon") ?? "";
    const markup = ICONS[name];
    if (!markup || group.childElementCount > 0) continue;

    group.innerHTML = markup;
    // The glyphs are stroked, so an inherited fill would flood them solid.
    const colour = group.getAttribute("fill") || group.getAttribute("stroke") || "currentColor";
    group.setAttribute("fill", "none");
    group.setAttribute("stroke", colour);
    group.setAttribute("stroke-width", "2");
    group.setAttribute("stroke-linecap", "round");
    group.setAttribute("stroke-linejoin", "round");
    resolved += 1;
  }

  return resolved;
}
